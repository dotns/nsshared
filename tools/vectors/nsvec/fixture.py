"""The `.vec` fixture text format shared by every producer.

Header comment lines start with `#`; vectors are separated by one blank line; each line is
`key = value` with bytes as lowercase hex, integers in decimal and text verbatim to the end
of the line. Every vector starts with `name = ...`; negative vectors carry
`expect = reject` and `reason = ...`.
"""

from . import DOCS_PIN


def _value(value):
    if isinstance(value, bool):
        raise TypeError("booleans have no fixture form")
    if isinstance(value, int):
        return str(value)
    if isinstance(value, (bytes, bytearray)):
        text = bytes(value).hex()
    elif isinstance(value, str):
        text = value
    else:
        raise TypeError(f"{type(value).__name__} has no fixture form")
    if not text or text != text.strip() or "\n" in text or "\r" in text:
        raise ValueError(f"fixture value {text!r} is empty, padded or multi-line")
    return text


def render(title, sections, vectors):
    """Renders a fixture file: `vectors` is a list of lists of (key, value) pairs."""
    lines = [
        f"# {title}",
        "# Generated by tools/vectors/generate.py; do not edit.",
        f"# Specification: dotns docs {DOCS_PIN}, {sections}.",
        "# Regenerate with `just vectors`; verify with `just vectors-check`.",
    ]
    names = set()
    for vector in vectors:
        if not vector or vector[0][0] != "name":
            raise ValueError("every vector starts with a name line")
        name = vector[0][1]
        if name in names:
            raise ValueError(f"duplicate vector name {name}")
        names.add(name)
        lines.append("")
        for key, value in vector:
            if not key or " " in key or key.startswith("#"):
                raise ValueError(f"bad fixture key {key!r}")
            lines.append(f"{key} = {_value(value)}")
    return "\n".join(lines) + "\n"
